import Foundation
import MijiaCore
import MijiaHomeKitBridge
import MijiaLAN

/// The app and packet-tunnel extension host the exact same runtime, with explicit executor labels.
@MainActor
public final class PrototypeRuntime {
    public let devices: DeviceController
    public let bridge: HomeKitBridgeController
    public let home: HomeStore
    public let configuration: PrototypeConfiguration
    public private(set) var evidence: PrototypeEvidence
    private let storage: PrototypeStorage
    private let api: LANMiotAPI
    private let transport: AuditedTransport
    private var task: Task<Void, Never>?
    private var savedPairingCode: String?

    public init(configuration: PrototypeConfiguration, executor: PrototypeExecutor, storage: PrototypeStorage,
                defaults: UserDefaults, bridgeVault: HomeKitBridgeVault? = nil,
                transport customTransport: (any MiioTransport)? = nil, loopbackOnly: Bool = false,
                networkSettings: TunnelNetworkSummary? = nil) throws {
        let config = try configuration.validated()
        self.configuration = config; self.storage = storage
        evidence = PrototypeEvidence(executor: executor, fixture: config.fixture)
        evidence.networkSettings = networkSettings
        evidence.transportKind = config.fixture ? (config.fixtureUDPHost == nil ? "memoryFixture" : "udpFixture") : "udpDevice"
        evidence.fixtureSelfTestWrites = config.fixtureSelfTestWrites == true
        let inner: any MiioTransport = customTransport ?? (config.fixture && config.fixtureUDPHost == nil ? FixtureTransport() : UDPMiioTransport())
        let audited = AuditedTransport(inner: inner, config: config, storage: storage)
        transport = audited
        let api = LANMiotAPI(config: { config.home }, transport: audited)
        self.api = api
        let devices = DeviceController(api: api, config: { config.home })
        self.devices = devices
        home = HomeStore(provider: CapabilityHomeProvider(controller: devices), defaultsSuiteName: storage.namespace + ".home")
        bridge = HomeKitBridgeController(vault: bridgeVault ?? HomeKitBridgeVault(
            load: { storage.readSecret("bridge-identity") },
            save: { storage.writeSecret($0, account: "bridge-identity") }
        ), defaults: defaults, loopbackOnly: loopbackOnly)
        bridge.keepsMacAwake = false
        bridge.isEnabled = true
    }

    public func start() async throws {
        guard task == nil else { return }
        bridge.attach(to: home, capabilities: devices)
        await devices.refreshNow()
        await bridge.waitUntilIdle()
        try await publish()
        task = Task { [weak self] in
            while !Task.isCancelled {
                guard let seconds = self?.configuration.pollSeconds else { return }
                do { try await Task.sleep(for: .seconds(seconds)) } catch { return }
                guard !Task.isCancelled, let self else { return }
                // Exercise only the canonical public-token UDP fixture. These writes are
                // generated by this self-test timer, not by an external HomeKit controller.
                if self.configuration.fixtureSelfTestWrites == true && self.storage.lifecycle()?.phase == "background" {
                    _ = await self.handle(.power(did: "77", on: !(self.evidence.devices.first?.isOn ?? false)))
                }
                try? await self.publish()
            }
        }
    }

    public func stop() async {
        task?.cancel(); task = nil
        bridge.isEnabled = false
        await bridge.waitUntilIdle()
        devices.shutdown()
        await api.shutdown()
        evidence.stoppedAt = Date()
        try? await publish()
    }

    public func handle(_ request: PrototypeRequest) async -> PrototypeReply {
        do {
            switch request {
            case .status: break
            case .refresh: await devices.refreshNow()
            case .power(let did, let on):
                guard let power = devices.snapshots[did]?.primaryPower, power.writable else { throw PrototypeError.noPower }
                try await devices.execute(did: did, .set(power.id, .bool(on)))
                await devices.refreshNow()
            case .diagnostics(let id):
                await devices.refreshNow()
                await bridge.waitUntilIdle()
                try await publish()
                let report = PrototypeDiagnostics.capture(id: id, configuration: configuration, evidence: evidence,
                    snapshots: Array(devices.snapshots.values), retries: devices.retryStates,
                    failures: bridge.readFailures, accessories: bridge.exposedDeviceCount,
                    revisions: (devices.structureRevision, devices.valuesRevision), pairingCode: bridge.setupCode)
                // Keep the provider reply small. The app checks this request UUID when reading
                // the atomic App Group file, so a failed request cannot export a stale report.
                try storage.saveDiagnostics(report)
                return PrototypeReply(evidence: evidence)
            }
            try await publish()
            return PrototypeReply(evidence: evidence)
        } catch { return PrototypeReply(evidence: evidence, error: error.localizedDescription) }
    }

    public func systemEvent(_ event: String) async {
        evidence.lastSystemEvent = event
        if event == "wake" { await devices.refreshNow() }
        try? await publish()
    }

    private func publish() async throws {
        let counts = await transport.counts
        let now = Date()
        if evidence.heartbeat > 0 { evidence.largestHeartbeatGap = max(evidence.largestHeartbeatGap, now.timeIntervalSince(evidence.updatedAt)) }
        evidence.updatedAt = now; evidence.heartbeat += 1
        evidence.appPhase = storage.lifecycle()?.phase ?? "unknown"
        evidence.authenticatedReads = counts.reads; evidence.acknowledgedWrites = counts.writes
        evidence.backgroundReads = counts.backgroundReads; evidence.backgroundWrites = counts.backgroundWrites
        evidence.transportFailures = counts.failures
        evidence.lastAuthenticatedReadAt = counts.lastRead; evidence.lastAcknowledgedWriteAt = counts.lastWrite
        switch bridge.status {
        case .stopped: evidence.bridgeStatus = "stopped"; evidence.bridgePort = nil
        case .waitingForDevices: evidence.bridgeStatus = "waiting"
        case .starting: evidence.bridgeStatus = "starting"
        case .running(let port): evidence.bridgeStatus = "running"; evidence.bridgePort = port
        case .failed(let message): evidence.bridgeStatus = "failed: \(message)"
        }
        evidence.paired = bridge.isPaired
        evidence.devices = configuration.home.devices.compactMap { device in
            guard let snapshot = devices.snapshots[device.did] else { return nil }
            return DeviceEvidence(id: device.did, name: device.name, online: snapshot.isOnline,
                isOn: snapshot.primaryPower.flatMap { snapshot.value($0.id)?.boolValue },
                lastReadingAt: snapshot.readings.values.compactMap(\.updatedAt).max())
        }
        try storage.saveEvidence(evidence)
        if savedPairingCode != bridge.setupCode {
            try storage.savePairingCode(bridge.setupCode)
            savedPairingCode = bridge.setupCode
        }
    }
}
